from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel


class TrendingItem(SdkBaseModel):
    """List of Qualified Items"""

    category_name: Optional[str] = Field(default=UNSET, alias="categoryName")
    """The categories this item belongs to"""

    department_name: Optional[str] = Field(default=UNSET, alias="departmentName")
    """The department this product belongs to"""

    isbn: Optional[str] = UNSET
    """International Standard Book Number"""

    product_name: Optional[str] = Field(default=UNSET, alias="productName")
    """A seller-specified, alphanumeric string uniquely identifying the product name"""

    is_two_day_eligible: Optional[int] = Field(default=UNSET, alias="isTwoDayEligible")
    """if the item can be shipped in two days"""

    item_id: Optional[str] = Field(default=UNSET, alias="itemId")
    """Specifies the item identifier generated by Walmart"""

    total_offers: Optional[int] = Field(default=UNSET, alias="totalOffers")
    """Total number of item stored by seller"""

    issn: Optional[str] = UNSET
    """International Standard Serial Number"""

    exists_for_seller: Optional[int] = Field(default=UNSET, alias="existsForSeller")
    """if seller is selling this item"""

    rank: Optional[int] = UNSET
    """Level of trending for this item"""

    brand: Optional[str] = UNSET
    """Specifies the item brand"""

    super_department_name: Optional[str] = Field(default=UNSET, alias="superDepartmentName")
    """The superDepartmentName this item belongs to"""

    sub_category_name: Optional[str] = Field(default=UNSET, alias="subCategoryName")
    """The subCategoryName this item belongs to"""


class TrendingItemDict(TypedDict):
    category_name: NotRequired[str]
    department_name: NotRequired[str]
    isbn: NotRequired[str]
    product_name: NotRequired[str]
    is_two_day_eligible: NotRequired[int]
    item_id: NotRequired[str]
    total_offers: NotRequired[int]
    issn: NotRequired[str]
    exists_for_seller: NotRequired[int]
    rank: NotRequired[int]
    brand: NotRequired[str]
    super_department_name: NotRequired[str]
    sub_category_name: NotRequired[str]
