from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel


class Insight1(SdkBaseModel):
    estimated_sales_lift: Optional[float] = Field(default=UNSET, alias="estimatedSalesLift")
    """The sales lift we predict you’ll see after your recommended items are converted, sent to WFS and made available
    to sell."""

    suggested_units: Optional[float] = Field(default=UNSET, alias="suggestedUnits")
    """The number of units Walmart suggests you send to WFS based on the item's forecasted sales demand. These
    suggestions are generated by algorithms considering several factors including past sales, seasonality, listing,
    quality, pricing, and more."""

    customer_favorite: Optional[bool] = Field(default=UNSET, alias="customerFavorite")
    """Indicates whether the item is identified as a customer favorite based on customer demand."""


class Insight1Dict(TypedDict):
    estimated_sales_lift: NotRequired[float]
    suggested_units: NotRequired[float]
    customer_favorite: NotRequired[bool]
