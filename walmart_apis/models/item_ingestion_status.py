from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .enums.ingestion_status import IngestionStatusOrStr
from .ingestion_errors import IngestionErrors, IngestionErrorsDict


class ItemIngestionStatus(SdkBaseModel):
    """The ingestion status of an individual item."""

    mart_id: Optional[int] = Field(default=UNSET, alias="martId")
    """Mart ID that a user or seller uses for a marketplace."""

    sku: Optional[str] = UNSET
    """An arbitrary alphanumeric unique ID, seller-specified, identifying each item."""

    wpid: Optional[str] = UNSET
    """An alphanumeric product ID, generated by Walmart."""

    index: Optional[int] = UNSET
    """index of items in the feed."""

    ingestion_status: IngestionStatusOrStr = Field(alias="ingestionStatus")
    """Can be one of the following: DATA_ERROR, SYSTEM_ERROR, TIMEOUT_ERROR, or INPROGRESS"""

    pending_status_description: Optional[str] = Field(default=UNSET, alias="pendingStatusDescription")
    """If the item is undergoing a compliance review, provides details about the review status, editing restrictions,
    and expected review timeframe."""

    ingestion_errors: Optional[IngestionErrors] = Field(default=UNSET, alias="ingestionErrors")
    """List of errors for an item."""


class ItemIngestionStatusDict(TypedDict):
    mart_id: NotRequired[int]
    sku: NotRequired[str]
    wpid: NotRequired[str]
    index: NotRequired[int]
    ingestion_status: IngestionStatusOrStr
    pending_status_description: NotRequired[str]
    ingestion_errors: NotRequired[IngestionErrorsDict]
