from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel


class Insight(SdkBaseModel):
    days_of_supply: Optional[int] = Field(default=UNSET, alias="daysOfSupply")
    """The anticipated number of days your current available and inbound inventory will last, based on your daily
    forecasted sales demand."""

    suggested_units: Optional[int] = Field(default=UNSET, alias="suggestedUnits")
    """The number of units Walmart suggests you send to WFS based on the item's forecasted sales demand. These
    suggestions are generated by algorithms considering several factors including past sales, seasonality, listing,
    quality, pricing, and more."""

    forecasted_sales_lift: Optional[float] = Field(default=UNSET, alias="forecastedSalesLift")
    """Estimated dollar amount in sales if the suggested number of units are sent to WFS and sold within 8 weeks."""

    customer_favorite: Optional[bool] = Field(default=UNSET, alias="customerFavorite")
    """Indicates whether the item is identified as a customer favorite based on customer demand."""


class InsightDict(TypedDict):
    days_of_supply: NotRequired[int]
    suggested_units: NotRequired[int]
    forecasted_sales_lift: NotRequired[float]
    customer_favorite: NotRequired[bool]
